def main():
    with open(PATH, "r") as f:
        data = json.load(f)
    
    for i, entry in enumerate(data["items"]):
        item_id = entry["id"]
        if item_id in TRANSLATIONS:
            name_cn, desc_cn = TRANSLATIONS[item_id]
            orig_name = entry.get("name", "")
            orig_desc = entry.get("description", "")
            if orig_name:
                entry["name_en"] = orig_name
                entry["name"] = name_cn
            if orig_desc:
                entry["description_en"] = orig_desc
                entry["description"] = desc_cn
        else:
            print(f"  ⚠ Missing translation for ID {item_id}: {entry.get('name', '?')}")
    
    with open(PATH, "w") as f:
        json.dump(data, f, indent=4, ensure_ascii=False)
    
    print(f"✓ Updated {len(data['items'])} items in mmo_items.json")


if __name__ == "__main__":
    main()
